// Danh sách tên toàn bộ tỉnh/thành phố để hiển thị
export function getAllProvinces(): string[] {
  return VIETNAM_PROVINCES.map((p) => p.name);
}

// Lấy danh sách quận/huyện theo tên tỉnh
export function getDistrictsByProvince(provinceName: string): string[] {
  if (!provinceName) return [];
  const found = VIETNAM_PROVINCES.find(
    (p) => p.name.trim().toLowerCase() === provinceName.trim().toLowerCase()
  );
  return found ? found.districts.map((d) => d.name) : [];
}

// Lấy danh sách phường/xã theo tỉnh và quận/huyện
export function getWardsByDistrict(provinceName: string, districtName: string): string[] {
  if (!provinceName || !districtName) return [];
  const prov = VIETNAM_PROVINCES.find(
    (p) => p.name.trim().toLowerCase() === provinceName.trim().toLowerCase()
  );
  if (!prov) return [];

  const dist = prov.districts.find(
    (d) => d.name.trim().toLowerCase() === districtName.trim().toLowerCase()
  );
  return dist ? dist.wards : [];
}
